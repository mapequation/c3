"""The Python port gives the results of the npm package on the shared fixtures.

fixtures/c3.json is generated by the TypeScript library (`pnpm --filter @mapequation/c3 fixtures`).
The two use their own languages' math, so hex colors may differ by 1 in an RGB channel
and other numbers by a small tolerance. The hue of a grey is not compared.
"""

from __future__ import annotations

import json
import math
import re
from pathlib import Path

import pytest

import c3

FIXTURES = Path(__file__).resolve().parents[2] / "fixtures" / "c3.json"
CASES = json.loads(FIXTURES.read_text())
HEX = re.compile(r"#[0-9a-f]{6}")
CHANNEL_TOLERANCE = 1
RELATIVE_TOLERANCE = 1e-9
ABSOLUTE_TOLERANCE = 1e-12  # for coordinates near zero, like a and b of greys
GREY_CHROMA = 1e-6  # below it, a color's hue is rounding noise that differs between platforms


def snake(value):
    """TypeScript option and field names to Python ones, like lightnessOffset to lightness_offset."""
    if isinstance(value, dict):
        return {re.sub(r"(?<!^)(?=[A-Z])", "_", key).lower(): snake(v) for key, v in value.items()}
    if isinstance(value, list):
        return [snake(v) for v in value]
    return value


def channels(color: str) -> list[int]:
    return [int(color[i : i + 2], 16) for i in (1, 3, 5)]


def differences(actual, expected, path="$"):
    """Where actual differs from expected: hex colors and numbers within the tolerances, other strings exactly."""
    if isinstance(expected, str) and HEX.fullmatch(expected):
        if isinstance(actual, str) and HEX.fullmatch(actual):
            if all(abs(a - e) <= CHANNEL_TOLERANCE for a, e in zip(channels(actual), channels(expected))):
                return []
        return [f"{path}: {actual!r} != {expected!r}"]
    if isinstance(expected, bool) or expected is None:
        return [] if actual is expected else [f"{path}: {actual!r} != {expected!r}"]
    if isinstance(expected, (int, float)):
        if isinstance(actual, (int, float)) and not isinstance(actual, bool):
            if math.isclose(actual, expected, rel_tol=RELATIVE_TOLERANCE, abs_tol=ABSOLUTE_TOLERANCE):
                return []
        return [f"{path}: {actual!r} != {expected!r}"]
    if isinstance(expected, list):
        if not isinstance(actual, (list, tuple)) or len(actual) != len(expected):
            return [f"{path}: {actual!r} != {expected!r}"]
        return [d for i, (a, e) in enumerate(zip(actual, expected)) for d in differences(a, e, f"{path}[{i}]")]
    if isinstance(expected, dict):
        if not isinstance(actual, dict) or set(actual) != set(expected):
            return [f"{path}: keys {sorted(actual) if isinstance(actual, dict) else actual!r} != {sorted(expected)}"]
        return [d for key in expected for d in differences(actual[key], expected[key], f"{path}.{key}")]
    return [] if actual == expected else [f"{path}: {actual!r} != {expected!r}"]


def run(case):
    fn, args, options = case["fn"], case["args"], snake(case["options"])
    if fn == "palette":
        return c3.palette(*args, **options)
    if fn == "hierarchy":
        colors = c3.hierarchy(*args, **options)
        return {
            "modules": colors.modules,
            "lookup": [{"path": item["path"], "color": colors(item["path"])} for item in case["expected"]["lookup"]],
        }
    if fn == "inferTone":
        return c3.infer_tone(*args)
    if fn == "oklab":
        return c3.oklab(*args)
    if fn == "oklch":
        return c3.oklch(*args)
    if fn == "distance":
        return c3.distance(*args)
    if fn == "tones":
        return c3.tones
    if fn == "swatches":
        return c3.swatches
    raise AssertionError(f"Unknown fixture function {fn}")


def test_fixtures_cover_the_public_api():
    assert {case["fn"] for case in CASES} == {
        "palette",
        "hierarchy",
        "inferTone",
        "oklab",
        "oklch",
        "distance",
        "tones",
        "swatches",
    }


@pytest.mark.parametrize("case", CASES, ids=[case["name"] for case in CASES])
def test_matches_typescript(case):
    expected = snake(case["expected"]) if case["fn"] in ("inferTone", "tones") else case["expected"]
    actual = run(case)
    if case["fn"] == "oklch" and expected[1] < GREY_CHROMA:
        # Greys have no hue: compare lightness and chroma only
        actual, expected = actual[:2], expected[:2]
    found = differences(actual, expected)
    assert not found, f"{case['name']} differs from the npm package at\n" + "\n".join(found)


def test_tolerates_one_per_channel_but_not_more():
    assert differences(["#2b9bea"], ["#2c9ae9"]) == []
    assert differences({"color": "#2b9bea"}, {"color": "#2d9bea"}) == ["$.color: '#2b9bea' != '#2d9bea'"]
    assert differences(["#2b9bea", "#000000"], ["#2b9bea", "#000002"]) == ["$[1]: '#000000' != '#000002'"]
